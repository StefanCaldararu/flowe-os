// The one and only TU that includes the font data headers.
//
// M2.1c flash diet: the headers are ASCII (U+0020..U+007E) subsets generated
// by tools/subset_epd_font.py from the read-only x4-os builtin fonts (see the
// regeneration command in each header). Non-ASCII codepoints have no glyph
// and render as '?' via the Gfx findGlyph fallback. Only the
// Bitmaps/Glyphs/Intervals arrays are emitted; the originals' kern/ligature
// tables were unreferenced (gc-sections discarded them) and are gone.
//
// lineAdvance/ascender come from the original headers' (discarded)
// EpdFontData initializers: both ubuntu_12 styles are {advanceY=29,
// ascender=24, descender=-5}.

#include "Fonts.h"

// UI typeface. Ubuntu Mono by default; build with -DXP_UI_FONT_MONO=0 for
// the original proportional Ubuntu. Both are generated by
// tools/gen_epd_font.py from the TTF at the same point sizes. The Mono
// headers keep Ubuntu's line metrics below (advanceY/ascender) rather than
// their own tighter ones (25/21 at 12pt, 21/18 at 10pt), so every scene's
// vertical layout and baselines stay exactly where they were.
#ifndef XP_UI_FONT_MONO
#define XP_UI_FONT_MONO 1
#endif

#if XP_UI_FONT_MONO
#include "fonts/ubuntumono_10_regular.h"
#include "fonts/ubuntumono_12_bold.h"
#include "fonts/ubuntumono_12_regular.h"
#define XP_UI_FACE(name) ubuntumono_##name
#else
#include "fonts/ubuntu_10_regular_ascii.h"
#include "fonts/ubuntu_12_bold_ascii.h"
#include "fonts/ubuntu_12_regular_ascii.h"
#define XP_UI_FACE(name) ubuntu_##name
#endif

const XpFont kFontRegular = {
    XP_UI_FACE(12_regularBitmaps),
    XP_UI_FACE(12_regularGlyphs),
    XP_UI_FACE(12_regularIntervals),
    sizeof(XP_UI_FACE(12_regularIntervals)) / sizeof(XP_UI_FACE(12_regularIntervals)[0]),
    29,  // advanceY
    24,  // ascender
};

const XpFont kFontBold = {
    XP_UI_FACE(12_boldBitmaps),
    XP_UI_FACE(12_boldGlyphs),
    XP_UI_FACE(12_boldIntervals),
    sizeof(XP_UI_FACE(12_boldIntervals)) / sizeof(XP_UI_FACE(12_boldIntervals)[0]),
    29,  // advanceY
    24,  // ascender
};

// M3 soft-key bar labels. Metrics from the original ubuntu_10_regular.h
// EpdFontData initializer (x4-os builtinFonts): advanceY=24, ascender=20.
const XpFont kFontSmall = {
    XP_UI_FACE(10_regularBitmaps),
    XP_UI_FACE(10_regularGlyphs),
    XP_UI_FACE(10_regularIntervals),
    sizeof(XP_UI_FACE(10_regularIntervals)) / sizeof(XP_UI_FACE(10_regularIntervals)[0]),
    24,  // advanceY
    20,  // ascender
};
